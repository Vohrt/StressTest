"""Generate reference zlib streams with Python's zlib (the same library AIDA64
pins, 1.2.5-compatible format) and write them as a C array for the inflate
conformance test."""
import zlib

CASES = [
    ("empty", b""),
    ("one", b"t"),
    ("two", b"th"),
    ("three", b"tha"),
    ("five", b"that "),
    ("abc", b"abc"),
    ("text", b"the quick brown fox jumps over the lazy dog " * 40),
    ("repeat", b"ab" * 5000),
    ("randomish", bytes((i * 37 + 11) & 0xFF for i in range(20000))),
]

lines = []
lines.append("// Generated by tools/gen_zlib_ref.py -- reference zlib streams.")
lines.append("// Decoded by inflate() as a conformance check; do not edit by hand.")
lines.append("#pragma once")
lines.append("#include <cstddef>")
lines.append("#include <cstdint>")
lines.append("")
lines.append("struct ZlibRefCase { const char* name; const uint8_t* data; size_t n;")
lines.append("                     const uint8_t* plain; size_t plain_n; };")
lines.append("")
for idx, (name, plain) in enumerate(CASES):
    comp = zlib.compress(plain, 6)
    lines.append("static const uint8_t kRef%d[] = {%s};" %
                 (idx, ",".join(str(b) for b in comp)))
    lines.append("static const uint8_t kPlain%d[] = {%s};" %
                 (idx, (",".join(str(b) for b in plain) if plain else "0")))
lines.append("")
lines.append("static const ZlibRefCase kZlibRefCases[] = {")
for idx, (name, plain) in enumerate(CASES):
    lines.append('    {"%s", kRef%d, sizeof(kRef%d), kPlain%d, %d},' %
                 (name, idx, idx, idx, len(plain)))
lines.append("};")
lines.append("static const size_t kZlibRefCount = %d;" % len(CASES))
lines.append("")

open(r"C:\Users\Voheart\source\repos\CpuStressTest\tools\zlib_ref.h", "w",
     encoding="utf-8", newline="").write("\n".join(lines))
print("wrote tools/zlib_ref.h with", len(CASES), "cases")
for name, plain in CASES:
    print(f"  {name:10s} plain={len(plain):7d} compressed={len(zlib.compress(plain, 6)):7d}")
